"""Copy the agent's model list and error catalog into the static portal, which publishes only portal/.

    python scripts/sync_portal_data.py          write portal/lab-data.js
    python scripts/sync_portal_data.py --check  fail if it is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "portal/lab-data.js"
MODEL_FIELDS = ("ollama_tag", "family", "about", "params_b", "quant", "size_gb", "min_ram_gb", "license_gate")
ERROR_FIELDS = ("id", "title", "patterns", "cause", "fix", "learn")


def render() -> str:
    models = json.loads((ROOT / "agent/skill/models.json").read_text(encoding="utf-8"))["models"]
    errors = json.loads((ROOT / "agent/skill/error_catalog.json").read_text(encoding="utf-8"))["errors"]
    data = {"models": [{k: m[k] for k in MODEL_FIELDS} for m in models],
            "errors": [{k: e[k] for k in ERROR_FIELDS} for e in errors]}
    return ("/* Generated by scripts/sync_portal_data.py from agent/skill. Do not edit. */\n"
            "globalThis.LocalLabCatalog = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")


def main(check: bool = False) -> int:
    if check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != render():
            print("portal/lab-data.js is out of date. Run: python scripts/sync_portal_data.py")
            return 1
        return 0
    TARGET.write_text(render(), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
